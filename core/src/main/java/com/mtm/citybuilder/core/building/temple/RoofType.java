package com.mtm.citybuilder.core.building.temple;

/** Roof forms of temple buildings. */
public enum RoofType {
    /** 寄棟: four slopes; on a square, a pyramid. */
    HIP,
    /** 切妻: two slopes, gable walls at the ends. */
    GABLE,
    /** 入母屋: hipped at the ends below, a gable above. */
    IRIMOYA
}
